/**
 * One-off asset preparation (run with `npm run assets`).
 *
 * - Builds the compact WebGL texture used by the procedural hero pour from the
 *   original product cutout in /products.
 * - Builds web-sized logo variants + app icon from /public/logo.png.
 *
 * Originals are never modified. Outputs are committed so the site works
 * without running this script; re-run it if the source images change.
 */
import sharp from "sharp";
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const out = (...p) => path.join(root, "public", ...p);

async function main() {
  await mkdir(out("hero", "procedural"), { recursive: true });
  await mkdir(out("brand"), { recursive: true });

  // Hero bottle texture: keep the full 1024x1536 canvas so the UV maths in
  // components/hero/procedural/choreography.ts (measured in source pixels) stays valid.
  await sharp(path.join(root, "products", "Luxury Faceted Tequila Decanter.png"))
    .webp({ quality: 88, alphaQuality: 95, effort: 6 })
    .toFile(out("hero", "procedural", "bottle.webp"));

  // Coarse alpha mask of the bottle (48×72) used to keep the liquid line level
  // and volume-correct as the bottle tilts. Precomputed so the browser never
  // has to read pixels back at runtime.
  const GW = 48;
  const GH = 72;
  const { data } = await sharp(path.join(root, "products", "Luxury Faceted Tequila Decanter.png"))
    .resize(GW, GH, { fit: "fill" })
    .ensureAlpha()
    .extractChannel(3)
    .raw()
    .toBuffer({ resolveWithObject: true });
  let bits = "";
  for (let i = 0; i < GW * GH; i++) bits += data[i] >= 140 ? "1" : "0";
  // Pack as hex nibbles to keep the generated file small.
  let hex = "";
  for (let i = 0; i < bits.length; i += 4) hex += parseInt(bits.slice(i, i + 4).padEnd(4, "0"), 2).toString(16);
  await writeFile(
    path.join(root, "components", "hero", "engines", "procedural", "bottleMask.ts"),
    `// Generated by scripts/prepare-assets.mjs. Do not edit by hand.\n` +
      `/** ${GW}×${GH} alpha mask of the hero bottle, 1 bit per cell, hex-packed row-major. */\n` +
      `export const BOTTLE_MASK = { w: ${GW}, h: ${GH}, hex: "${hex}" } as const;\n`,
  );

  // Logo variants.
  const logo = path.join(root, "public", "logo.png");
  for (const size of [128, 256, 512]) {
    await sharp(logo).resize(size, size).webp({ quality: 90 }).toFile(out("brand", `logo-${size}.webp`));
  }
  // App icon (Next.js picks up app/icon.png automatically).
  await sharp(logo)
    .resize(256, 256)
    .flatten({ background: "#0b0a09" })
    .png({ compressionLevel: 9, palette: true })
    .toFile(path.join(root, "app", "icon.png"));

  await prepareProducts();
  await prepareOgImage();

  console.log("Assets prepared.");
}

/**
 * Product imagery: trims each cutout to its visible bounds (ignoring faint
 * specks left by the cut-out), adds even padding so every bottle frames the
 * same way, and writes web-sized WebP + a generated metadata module with
 * dimensions and a tiny blur placeholder.
 */
const PRODUCT_SOURCES = {
  "reserva-huizar-cristalino-reposado": "Luxury Faceted Tequila Decanter",
  "reserva-huizar-plata": "Cobalt Blue Reserva Tequila Decanter",
  "reserva-huizar-plata-rosado": "Magenta Faceted Tequila Decanter",
  "casa-cofradia-anejo-black": "Casa Cofrad",
  "la-cofradia-las-iguanas-reposado": "Ornate Talavera Iguana",
  "reserva-huizar-tasting-trio": "Luxury Three-Bottle Tequila Gift Set",
  "pechery-dubai-chocolate-cream-liqueur": "Dubai Style Chocolate Liqueur",
};

async function prepareProducts() {
  const srcDir = path.join(root, "products");
  const outDir = out("products");
  await mkdir(outDir, { recursive: true });
  const files = await readdir(srcDir);
  const meta = {};

  for (const [slug, prefix] of Object.entries(PRODUCT_SOURCES)) {
    const file = files.find((f) => f.normalize("NFC").startsWith(prefix.normalize("NFC")) && f.endsWith(".png"));
    if (!file) throw new Error(`No source image for ${slug}`);
    const src = path.join(srcDir, file);

    // Clean faint alpha specks, then find the real bounds.
    const { data, info } = await sharp(src).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    let minX = info.width, minY = info.height, maxX = 0, maxY = 0;
    for (let y = 0; y < info.height; y++) {
      for (let x = 0; x < info.width; x++) {
        const i = (y * info.width + x) * 4 + 3;
        if (data[i] < 12) {
          data[i] = 0;
          continue;
        }
        if (data[i] > 60) {
          if (x < minX) minX = x;
          if (x > maxX) maxX = x;
          if (y < minY) minY = y;
          if (y > maxY) maxY = y;
        }
      }
    }
    const w = maxX - minX + 1;
    const h = maxY - minY + 1;
    const pad = Math.round(Math.max(w, h) * 0.04);
    const cleaned = sharp(data, { raw: info })
      .extract({ left: minX, top: minY, width: w, height: h })
      .extend({ top: pad, bottom: pad, left: pad, right: pad, background: { r: 0, g: 0, b: 0, alpha: 0 } });
    const buf = await cleaned.png().toBuffer();

    const maxH = 1500;
    const resized = sharp(buf).resize({ height: Math.min(maxH, h + pad * 2), withoutEnlargement: true });
    const outFile = path.join(outDir, `${slug}.webp`);
    const res = await resized.webp({ quality: 86, alphaQuality: 92, effort: 6 }).toFile(outFile);

    const blur = await sharp(buf).resize({ width: 16 }).webp({ quality: 40 }).toBuffer();
    meta[slug] = {
      src: `/products/${slug}.webp`,
      width: res.width,
      height: res.height,
      blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
    };
  }

  await writeFile(
    path.join(root, "lib", "product-images.ts"),
    `// Generated by scripts/prepare-assets.mjs. Do not edit by hand.\n` +
      `export interface ProductImage { src: string; width: number; height: number; blurDataURL: string }\n\n` +
      `export const PRODUCT_IMAGES = ${JSON.stringify(meta, null, 2)} as const satisfies Record<string, ProductImage>;\n\n` +
      `export type ProductImageKey = keyof typeof PRODUCT_IMAGES;\n`,
  );
}

/** 1200×630 Open Graph card: dark stage, the hero bottle, logo and tagline. */
async function prepareOgImage() {
  const W = 1200;
  const H = 630;
  const bg = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">
    <defs>
      <radialGradient id="g" cx="0.72" cy="0.45" r="0.6"><stop offset="0" stop-color="#5a3a14"/><stop offset="0.55" stop-color="#1a120a"/><stop offset="1" stop-color="#0b0a09"/></radialGradient>
    </defs>
    <rect width="100%" height="100%" fill="url(#g)"/>
    <line x1="80" y1="470" x2="560" y2="470" stroke="#c9a46a" stroke-opacity="0.5"/>
    <text x="80" y="330" font-family="Georgia, 'Times New Roman', serif" font-size="78" fill="#f3ebdd" font-weight="300">Pour something</text>
    <text x="80" y="420" font-family="Georgia, 'Times New Roman', serif" font-size="78" font-style="italic" fill="#e3a24a">real.</text>
    <text x="80" y="518" font-family="Helvetica, Arial, sans-serif" font-size="17" letter-spacing="4" fill="#e2c99b">ADDITIVE-FREE · 100% BLUE AGAVE · TORONTO</text>
    <text x="80" y="550" font-family="Helvetica, Arial, sans-serif" font-size="17" letter-spacing="4" fill="#b5aa99">CHOSEN BY CANADA'S ONLY CERTIFIED TEQUILA MASTER</text>
  </svg>`);
  const bottle = await sharp(path.join(root, "public", "products", "reserva-huizar-cristalino-reposado.webp")).resize({ height: 560 }).toBuffer();
  const logo = await sharp(path.join(root, "public", "logo.png")).resize(140, 140).toBuffer();
  await sharp(bg)
    .composite([
      { input: bottle, top: 40, left: 800 },
      { input: logo, top: 70, left: 80 },
    ])
    .jpeg({ quality: 86 })
    .toFile(path.join(root, "app", "opengraph-image.jpg"));
  await writeFile(path.join(root, "app", "opengraph-image.alt.txt"), "Eleva Imports: additive-free tequila chosen by Canada's only Certified Tequila Master");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
